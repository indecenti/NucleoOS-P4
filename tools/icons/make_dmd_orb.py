#!/usr/bin/env python3
"""The chrome orb of the DMD app's cabinet theme (the glass insert behind the selected wheel), from the
Qwen Image 2.1 render in tools/icons/qwen/dmd_orb_src.png (prompt in the same folder) to
components/nv_apps/dmd_orb.c: an LVGL RGB565A8 image, round alpha, ready to draw without any transform.

    python tools/icons/make_dmd_orb.py
"""
import os

from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "icons", "qwen", "dmd_orb_src.png")
OUT = os.path.join(ROOT, "components", "nv_apps", "dmd_orb.c")
SIZE = 156   # kBarImg (136) + a chrome rim around it


def main():
    im = Image.open(SRC).convert("RGB")
    # the ring: the bounding box of everything brighter than the black background
    lum = im.convert("L").point(lambda v: 255 if v > 40 else 0)
    x0, y0, x1, y1 = lum.getbbox()
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
    crop = im.crop((cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2))
    small = crop.resize((SIZE, SIZE), Image.LANCZOS)
    # round alpha, anti-aliased (drawn 4x, shrunk), a hair inside the chrome's outer edge
    big = Image.new("L", (SIZE * 4, SIZE * 4), 0)
    ImageDraw.Draw(big).ellipse((2, 2, SIZE * 4 - 3, SIZE * 4 - 3), fill=255)
    alpha = big.resize((SIZE, SIZE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.3))
    px, a = small.load(), alpha.load()
    rgb = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = px[x, y]
            v = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
            rgb += bytes((v & 255, v >> 8))
    al = bytes(a[x, y] for y in range(SIZE) for x in range(SIZE))
    data = bytes(rgb) + al
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by tools/icons/make_dmd_orb.py from tools/icons/qwen/dmd_orb_src.png (Qwen Image 2.1). Do not edit.\n")
        f.write("// The DMD app's cabinet theme: the chrome and glass orb behind the selected wheel, %dx%d RGB565A8.\n" % (SIZE, SIZE))
        f.write('#include "lvgl.h"\n\n')
        f.write("static const uint8_t kOrb[%d] = {\n%s\n};\n\n" % (len(data), "\n".join(lines)))
        f.write("const lv_image_dsc_t dmd_orb = {\n")
        f.write("    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = %d, .h = %d, .stride = %d},\n" % (SIZE, SIZE, SIZE * 2))
        f.write("    .data_size = sizeof kOrb,\n    .data = kOrb,\n};\n")
    print("wrote", OUT, len(data), "bytes")


if __name__ == "__main__":
    main()
