// hidpad_test — PC unit test of components/nv_hal/nv_hid_gamepad.c (the USB gamepad report
// descriptor parser + report decoder). Descriptors are written out item by item after the HID 1.11
// spec, covering the shapes real pads use: no report ID + stick, report ID + hat (DualShock 4
// style), the "255 in one byte" logical-maximum bug, D-pad usages, signed axes; a keyboard must be
// refused. Run (WSL/Linux):
//   gcc -O2 -Wall -Wextra -I components/nv_hal tools/hidpad_test/test.c components/nv_hal/nv_hid_gamepad.c -o /tmp/hidpad && /tmp/hidpad
#include "nv_hid_gamepad.h"

#include <stdio.h>

static int fails;
#define CHECK(c) do { if (!(c)) { printf("FAIL %s:%d  %s\n", __FILE__, __LINE__, #c); fails++; } } while (0)

static void decode(const nv_hid_pad_layout_t *l, const uint8_t *r, size_t n, uint8_t *d, uint32_t *b, bool expect) {
    *d = 0xff; *b = 0xffffffff;
    CHECK(nv_hid_pad_decode(l, r, n, d, b) == expect);
}

int main(void) {
    nv_hid_pad_layout_t l;
    uint8_t d;
    uint32_t b;

    // 1. Generic gamepad, no report ID: 8-bit X/Y 0..255, 10 buttons, 6 bits padding.
    static const uint8_t generic[] = {
        0x05, 0x01, 0x09, 0x05, 0xa1, 0x01,               // Desktop / Gamepad / Application
        0x15, 0x00, 0x26, 0xff, 0x00,                     //   logical 0..255
        0x09, 0x30, 0x09, 0x31, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02,   // X, Y: 2 x 8 bits
        0x05, 0x09, 0x19, 0x01, 0x29, 0x0a,               //   Button 1..10
        0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0a, 0x81, 0x02,
        0x75, 0x06, 0x95, 0x01, 0x81, 0x03,               //   padding (constant)
        0xc0 };
    CHECK(nv_hid_pad_parse(generic, sizeof generic, &l));
    CHECK(l.report_id == 0 && l.n_buttons == 10 && l.x.size == 8 && l.y.off == 8 && !l.hat.size);
    { const uint8_t r[] = { 0x80, 0x7f, 0x00, 0x00 }; decode(&l, r, sizeof r, &d, &b, true); CHECK(d == 0 && b == 0); }
    { const uint8_t r[] = { 0x00, 0xff, 0x01, 0x00 }; decode(&l, r, sizeof r, &d, &b, true);
      CHECK(d == (NV_PAD_LEFT | NV_PAD_DOWN) && b == 1); }
    { const uint8_t r[] = { 0xff, 0x00, 0x00, 0x02 }; decode(&l, r, sizeof r, &d, &b, true);
      CHECK(d == (NV_PAD_RIGHT | NV_PAD_UP) && b == (1u << 9)); }
    { const uint8_t r[] = { 0x50, 0xb0, 0x00, 0x00 }; decode(&l, r, sizeof r, &d, &b, true); CHECK(d == 0); }   // inside dead zone

    // 2. DualShock-4 style: report ID 1, four 8-bit axes, 4-bit hat with a null state, 14 buttons,
    //    a vendor counter; physical range / unit items in between; a feature report after.
    static const uint8_t ds4[] = {
        0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x85, 0x01,
        0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x15, 0x00, 0x26, 0xff, 0x00,
        0x75, 0x08, 0x95, 0x04, 0x81, 0x02,
        0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x35, 0x00, 0x46, 0x3b, 0x01, 0x65, 0x14,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
        0x65, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x0e, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x0e, 0x81, 0x02,
        0x06, 0x00, 0xff, 0x09, 0x20, 0x75, 0x06, 0x95, 0x01, 0x81, 0x02,
        0x85, 0x05, 0x09, 0x22, 0x75, 0x08, 0x95, 0x1f, 0xb1, 0x02,        // feature report 5
        0xc0 };
    CHECK(nv_hid_pad_parse(ds4, sizeof ds4, &l));
    CHECK(l.report_id == 1 && l.hat.off == 32 && l.hat.size == 4 && l.btn[0].off == 36 && l.n_buttons == 14);
    { const uint8_t r[] = { 0x01, 0x80, 0x80, 0x80, 0x80, 0x08, 0x00, 0x00 };   // centred, hat null
      decode(&l, r, sizeof r, &d, &b, true); CHECK(d == 0 && b == 0); }
    { const uint8_t r[] = { 0x01, 0x80, 0x80, 0x80, 0x80, 0x03 | 0x20, 0x00, 0x00 };   // hat SE, button 2
      decode(&l, r, sizeof r, &d, &b, true); CHECK(d == (NV_PAD_DOWN | NV_PAD_RIGHT) && b == 2); }
    { const uint8_t r[] = { 0x01, 0x80, 0x80, 0x80, 0x80, 0x06, 0x00, 0x02 };   // hat W, button 14
      decode(&l, r, sizeof r, &d, &b, true); CHECK(d == NV_PAD_LEFT && b == (1u << 13)); }
    { const uint8_t r[] = { 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };   // other report ID
      decode(&l, r, sizeof r, &d, &b, false); }
    { const uint8_t r[] = { 0x01 }; decode(&l, r, sizeof r, &d, &b, true); }   // truncated: reads as 0
    // 3. "255" written in one byte (reads -1): the range must still be 0..255.
    static const uint8_t bug[] = {
        0x05, 0x01, 0x09, 0x04, 0xa1, 0x01,               // Joystick
        0x15, 0x00, 0x25, 0xff, 0x09, 0x30, 0x09, 0x31, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x04, 0x25, 0x01, 0x75, 0x01, 0x95, 0x04, 0x81, 0x02,
        0x95, 0x04, 0x81, 0x01,
        0xc0 };
    CHECK(nv_hid_pad_parse(bug, sizeof bug, &l));
    CHECK(l.x.lmax == 255);
    { const uint8_t r[] = { 0x80, 0x00, 0x08 }; decode(&l, r, sizeof r, &d, &b, true); CHECK(d == NV_PAD_UP && b == 8); }

    // 4. D-pad as Generic Desktop usages 0x90..0x93, buttons as a usage list.
    static const uint8_t dpad[] = {
        0x05, 0x01, 0x09, 0x05, 0xa1, 0x01,
        0x09, 0x90, 0x09, 0x91, 0x09, 0x92, 0x09, 0x93, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x04, 0x81, 0x02,
        0x05, 0x09, 0x09, 0x01, 0x09, 0x02, 0x09, 0x03, 0x09, 0x04, 0x95, 0x04, 0x81, 0x02,
        0xc0 };
    CHECK(nv_hid_pad_parse(dpad, sizeof dpad, &l));
    { const uint8_t r[] = { 0x09 | 0x40 }; decode(&l, r, sizeof r, &d, &b, true);   // up + left, button 3
      CHECK(d == (NV_PAD_UP | NV_PAD_LEFT) && b == 4); }

    // 5. Signed axes -127..127 inside a Physical collection, 16-bit.
    static const uint8_t sgn[] = {
        0x05, 0x01, 0x09, 0x04, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00,
        0x16, 0x01, 0x80, 0x26, 0xff, 0x7f, 0x09, 0x30, 0x09, 0x31, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02,
        0xc0,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x02, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02,
        0x75, 0x06, 0x95, 0x01, 0x81, 0x03,
        0xc0 };
    CHECK(nv_hid_pad_parse(sgn, sizeof sgn, &l));
    CHECK(l.x.lmin == -32767 && l.y.off == 16 && l.btn[1].off == 33);
    { const uint8_t r[] = { 0x01, 0x80, 0xff, 0x7f, 0x02, 0x00 };   // x = -32767, y = 32767, button 2
      decode(&l, r, sizeof r, &d, &b, true); CHECK(d == (NV_PAD_LEFT | NV_PAD_DOWN) && b == 2); }
    { const uint8_t r[] = { 0x00, 0x10, 0x00, 0xf0, 0x00, 0x00 };   // small deflections: centred
      decode(&l, r, sizeof r, &d, &b, true); CHECK(d == 0); }

    // 6. A keyboard (and a mouse) are not gamepads.
    static const uint8_t kbd[] = {
        0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x05, 0x07, 0x19, 0xe0, 0x29, 0xe7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x06, 0x75, 0x08, 0x26, 0xff, 0x00, 0x19, 0x00,
        0x29, 0xff, 0x81, 0x00, 0xc0 };
    CHECK(!nv_hid_pad_parse(kbd, sizeof kbd, &l));
    static const uint8_t mouse[] = {
        0x05, 0x01, 0x09, 0x02, 0xa1, 0x01, 0x09, 0x01, 0xa1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
        0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7f, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
        0xc0, 0xc0 };
    CHECK(!nv_hid_pad_parse(mouse, sizeof mouse, &l));

    // 7. Garbage / truncated descriptors never read past the end.
    static const uint8_t trunc[] = { 0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x27, 0xff };
    CHECK(!nv_hid_pad_parse(trunc, sizeof trunc, &l));
    static const uint8_t longitem[] = { 0xfe, 0x40, 0x00 };
    CHECK(!nv_hid_pad_parse(longitem, sizeof longitem, &l));

    printf(fails ? "hidpad: %d FAILED\n" : "hidpad: all OK\n", fails);
    return fails != 0;
}
