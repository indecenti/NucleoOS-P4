"""Import the action corpora of the original NucleoOS (Cardputer) ANIMA as host test cases for the P4.

  python tools/import_nucleo_evals.py <path to NucleoOs checkout>
      -> tests/host/unit/anima_eval_cases.h   (read by tests/host/unit/test_anima_nl.cpp)

Sources, same engine lineage and author:
  tools/anima/eval_action.jsonl         curated stress: a statement or a negation that merely MENTIONS an
                                        action ("ho abbassato il volume ieri") must never run one
                                        (expect "tier:none"), plus the real commands
  tools/anima-host/action-phrases.jsonl  raw command phrasings per category (partly machine-made, some
                                        nonsense): measured as coverage, not a gate
Knowledge cases ("l1") are skipped: they need the SD knowledge packs, which the host test does not have.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "host", "unit", "anima_eval_cases.h")
EN = re.compile(r"\b(the|a|an|my|to|with|make|set|turn|open|create|remind|me|please|up|down|note|file|saying|volume|brightness|show|start|launch|tomorrow|at)\b")
IT = re.compile(r"[àèéìòù]|\b(il|lo|la|le|di|del|della|con|una|un|per|alza|abbassa|apri|crea|ricordami|domani|alle|nota|scrivi)\b")


def lang_of(q, given):
    if given in ("it", "en"):
        return given
    ql = q.lower()
    return "en" if len(EN.findall(ql)) > len(IT.findall(ql)) else "it"


def rows(path):
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("//"):
            yield json.loads(line)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    base = sys.argv[1]
    cases, seen = [], set()
    for rel, key in (("tools/anima/eval_action.jsonl", "expect"), ("tools/anima-host/action-phrases.jsonl", "cat")):
        for d in rows(os.path.join(base, rel)):
            exp = d.get(key)
            if not exp or exp == "l1" or d["q"] in seen:
                continue
            seen.add(d["q"])
            cases.append((lang_of(d["q"], d.get("lang")), d["q"], exp, rel.endswith("eval_action.jsonl")))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/import_nucleo_evals.py from the NucleoOS (Cardputer) ANIMA corpora - do not edit.\n")
        f.write("// expect = the intent L0 must produce, or \"tier:none\" = it must run NO action at all. strict = the\n"
                "// curated eval_action.jsonl (a gate); the rest is action-phrases.jsonl (raw, partly machine-made:\n"
                "// a coverage metric).\n#pragma once\n\n")
        f.write("struct EvalCase { bool en; const char *q; const char *expect; bool strict; };\n\nstatic const EvalCase kEvalCases[] = {\n")
        for lang, q, exp, strict in cases:
            f.write("    { %s, %s, %s, %s },\n" % ("true" if lang == "en" else "false", cstr(q), cstr(exp),
                                                "true" if strict else "false"))
        f.write("};\n")
    print("%d cases -> %s" % (len(cases), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
