// ANIMA L0 in natural language, Italian and English: the device-only rung (no model, no network) must
// keep understanding the ways people actually phrase a request — paraphrases, politeness, articles,
// punctuation, capitals — and must never leave the user with an empty reply. One table row per phrase;
// a regression prints the phrase and what L0 answered instead. Runs with the network mode OFF, as the
// "offline" setting on the device (docs/ANIMA_MODES.md).
