"""gen_icons.py — the interface icons of the Libri app, drawn here (no third-party artwork): 8-bit
coverage masks the app tints with the theme colours. The icons the Biblioteca app has are drawn by its
own gen_icons.py (ports/zim/biblioteca); the reader's own (bookmark, store, sort, trash, prev, next)
are drawn below with the same helpers.

    python ports/books/gen_icons.py OUT.h [PREVIEW.png]
"""
import importlib.util
import os
import sys

from PIL import Image, ImageDraw

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("bib_icons", os.path.join(here, "..", "zim", "biblioteca", "gen_icons.py"))
bib = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bib)


def draw(name, px):
    if name not in ("bookmark", "bookmark_on", "store", "sort", "trash", "prev", "next", "rotate"):
        return bib.draw(name, px)
    im = bib.canvas(px)
    d = ImageDraw.Draw(im)
    if name in ("bookmark", "bookmark_on"):   # a ribbon with a notch
        pts = [(6.5, 3), (17.5, 3), (17.5, 21), (12, 16.5), (6.5, 21)]
        bib.poly(d, px, pts, fill=name == "bookmark_on", w=1.9)
    elif name == "store":   # a bag with a handle
        bib.poly(d, px, [(4, 8), (20, 8), (19, 21), (5, 21)], fill=False, w=1.9)
        d.arc((*bib.P(px, 8, 3), *bib.P(px, 16, 12)), start=180, end=360, fill=255, width=bib.W(px, 1.9))
    elif name == "sort":   # lines getting shorter, an arrow down
        bib.line(d, px, [(4, 6), (14, 6)])
        bib.line(d, px, [(4, 12), (11, 12)])
        bib.line(d, px, [(4, 18), (8, 18)])
        bib.line(d, px, [(18, 5), (18, 19)])
        bib.line(d, px, [(15, 16), (18, 19.5), (21, 16)])
    elif name == "trash":
        bib.line(d, px, [(4, 6.5), (20, 6.5)])
        bib.line(d, px, [(9.5, 6), (10, 3.5), (14, 3.5), (14.5, 6)], w=1.7)
        bib.poly(d, px, [(6, 7), (18, 7), (17, 21), (7, 21)], fill=False, w=1.8)
        bib.line(d, px, [(10.5, 10.5), (10.5, 17.5)], w=1.5)
        bib.line(d, px, [(13.5, 10.5), (13.5, 17.5)], w=1.5)
    elif name == "rotate":   # a phone turning: a rounded rectangle and a curved arrow
        bib.rrect(d, px, 8, 3, 16, 21, 2, w=1.7)
        d.arc((*bib.P(px, 2, 2), *bib.P(px, 22, 22)), start=200, end=290, fill=255, width=bib.W(px, 1.7))
        bib.poly(d, px, [(9.5, 1.2), (12.5, 3.6), (9.2, 5.6)])
    elif name == "prev":
        bib.line(d, px, [(15, 5), (8, 12), (15, 19)], w=2.4)
    elif name == "next":
        bib.line(d, px, [(9, 5), (16, 12), (9, 19)], w=2.4)
    return im.resize((px, px), Image.BOX)


ICONS = [("back", 24), ("search", 24), ("toc", 24), ("bookmark", 24), ("bookmark_on", 24), ("more", 24), ("library", 24),
         ("info", 24), ("close", 24), ("textsize", 24), ("check", 24), ("backspace", 24), ("enter", 24), ("shift", 24),
         ("keyboard", 24), ("book", 48), ("download", 24), ("store", 24), ("sort", 24), ("trash", 24), ("prev", 24),
         ("next", 24), ("rotate", 24)]


def main():
    out = sys.argv[1]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by ports/books/gen_icons.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n")
        for name, px in ICONS:
            data = draw(name, px).tobytes()
            f.write("static const uint8_t ICON_%s[%d * %d] = {\n" % (name.upper(), px, px))
            for i in range(0, len(data), 24):
                f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
            f.write("};\n#define ICON_%s_PX %d\n\n" % (name.upper(), px))
    if len(sys.argv) > 2:
        sheet = Image.new("L", (len(ICONS) * 56, 56), 255)
        for i, (name, px) in enumerate(ICONS):
            im = draw(name, px)
            sheet.paste(Image.eval(im, lambda v: 255 - v), (i * 56 + (56 - px) // 2, (56 - px) // 2))
        sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(sys.argv[2])
    print("%s: %d icons" % (out, len(ICONS)))


if __name__ == "__main__":
    main()
