"""gen_text.py — a text file as a C string for the Libri app (the third-party notices).

    python ports/books/gen_text.py IN.txt OUT.c NAME
"""
import sys


def main():
    src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, "rb").read()
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by ports/books/gen_text.py from %s. Do not edit.\n" % src.replace("\\", "/").split("/")[-1])
        f.write("const char %s[] = {\n" % name)
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("    0};\n")


if __name__ == "__main__":
    main()
