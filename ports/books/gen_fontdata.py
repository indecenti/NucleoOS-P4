"""gen_fontdata.py — the fonts of the Libri app as C data, zlib-compressed (font.c inflates a face
the first time it is used): Noto Sans and Mono of the Biblioteca app, Noto Serif of ports/books/fonts.

    python ports/books/gen_fontdata.py OUT.c
"""
import os
import sys
import zlib

here = os.path.dirname(os.path.abspath(__file__))
bib = os.path.join(here, "..", "zim", "biblioteca", "fonts")
FACES = [   # the order of F_* in bk.h
    os.path.join(bib, "sans.ttf"), os.path.join(bib, "sans-bold.ttf"), os.path.join(bib, "sans-italic.ttf"),
    os.path.join(bib, "sans-bolditalic.ttf"), os.path.join(bib, "mono.ttf"),
    os.path.join(here, "fonts", "serif.ttf"), os.path.join(here, "fonts", "serif-bold.ttf"),
    os.path.join(here, "fonts", "serif-italic.ttf"), os.path.join(here, "fonts", "serif-bolditalic.ttf"),
]


def main():
    out = sys.argv[1]
    total = 0
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by ports/books/gen_fontdata.py. Do not edit.\n")
        f.write("typedef struct { const unsigned char *z; unsigned zn, n; } fontdata_t;\n\n")
        sizes = []
        for i, path in enumerate(FACES):
            raw = open(path, "rb").read()
            z = zlib.compress(raw, 9)
            total += len(z)
            sizes.append((len(z), len(raw)))
            f.write("static const unsigned char kFont%d[%d] = {\n" % (i, len(z)))
            for k in range(0, len(z), 32):
                f.write("    " + ",".join(str(b) for b in z[k:k + 32]) + ",\n")
            f.write("};\n")
        f.write("\nconst fontdata_t bk_fonts[%d] = {\n" % len(FACES))
        for i, (zn, n) in enumerate(sizes):
            f.write("    {kFont%d, %d, %d},\n" % (i, zn, n))
        f.write("};\n")
    print("%s: %d faces, %d bytes deflated" % (out, len(FACES), total))


if __name__ == "__main__":
    main()
