"""gen_hyph.py — the hyphenation patterns of the Libri app (hyph.c): fetched once into
ports/books/hyph/ (committed, with their license notices: the MIT, BSD and MPL terms want the source
and the notice kept), then written as zlib-compressed strings into OUT.c (the build puts it in _out/gen).

    python ports/books/gen_hyph.py OUT.c [--fetch]

Only patterns whose license allows them inside the app are here (docs/BOOKS_PLAN.md §1 D5):
MIT / BSD / permissive terms from TeX hyph-utf8, Swedish from LibreOffice under MPL. Left out on purpose: Hungarian (200 KB of patterns: the app's 2 MB cap), Russian and Catalan (LPPL only),
Finnish ("may be freely distributed", nothing about converting), Czech (GPL).
"""
import hashlib
import os
import re
import sys
import urllib.request
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(HERE, "hyph")
TEX = "https://raw.githubusercontent.com/hyphenation/tex-hyphen/master/hyph-utf8/tex/generic/hyph-utf8/patterns/tex/"
LO = "https://raw.githubusercontent.com/LibreOffice/dictionaries/master/"

# app language code: (source URL, file kept here, license chosen, left min, right min)
LANGS = {
    "it": (TEX + "hyph-it.tex", "hyph-it.tex", "MIT (of LPPL 1.3 / MIT)", 2, 2),
    "en": (TEX + "hyph-en-us.tex", "hyph-en-us.tex", "permissive (copyright notice kept)", 2, 3),
    "es": (TEX + "hyph-es.tex", "hyph-es.tex", "MIT", 2, 2),
    "fr": (TEX + "hyph-fr.tex", "hyph-fr.tex", "MIT", 2, 3),
    "de": (TEX + "hyph-de-1996.tex", "hyph-de-1996.tex", "MIT", 2, 2),
    "pt": (TEX + "hyph-pt.tex", "hyph-pt.tex", "BSD-3-Clause", 2, 3),
    "nl": (TEX + "hyph-nl.tex", "hyph-nl.tex", "MIT", 2, 2),
    "da": (TEX + "hyph-da.tex", "hyph-da.tex", "MIT (of LPPL 1.3 / MIT)", 2, 2),
    "pl": (TEX + "hyph-pl.tex", "hyph-pl.tex", "MIT (of MIT / Knuth terms)", 2, 2),
    "la": (TEX + "hyph-la.tex", "hyph-la.tex", "MIT (of MIT / LPPL)", 2, 2),
    "sv": (LO + "sv_SE/hyph_sv.dic", "hyph_sv.dic", "MPL (of MPL / LGPLv3+)", 2, 2),
}


def fetch():
    os.makedirs(DIR, exist_ok=True)
    for code, (url, name, _, _, _) in LANGS.items():
        path = os.path.join(DIR, name)
        if os.path.exists(path):
            continue
        with urllib.request.urlopen(url, timeout=60) as r:
            data = r.read()
        open(path, "wb").write(data)
        print("fetched", name, len(data), hashlib.sha256(data).hexdigest()[:16])
    if "hyph_sv.dic" in [v[1] for v in LANGS.values()]:   # its README holds the notice
        p = os.path.join(DIR, "README_hyph_sv.txt")
        if not os.path.exists(p):
            with urllib.request.urlopen(LO + "sv_SE/README_hyph_sv.txt", timeout=60) as r:
                open(p, "wb").write(r.read())


def tex_patterns(text):
    """The patterns of a hyph-utf8 .tex file: the body of \\patterns{...}, comments dropped."""
    m = re.search(r"\\patterns\s*\{(.*?)\}", text, re.S)
    if not m:
        raise SystemExit("no \\patterns block")
    out = []
    for line in m.group(1).split("\n"):
        line = line.split("%", 1)[0]
        out.extend(w for w in line.split() if w)
    return out


def dic_patterns(text):
    """The patterns of a hunspell/LibreOffice hyphen .dic (first line: the charset; options and
    patterns with non-standard parts skipped)."""
    out = []
    for i, line in enumerate(text.split("\n")):
        line = line.strip()
        if i == 0 or not line or line.startswith("%") or line.startswith("#"):
            continue
        if re.match(r"^[A-Z]+(HYPHENMIN|MIN)", line) or line.startswith("NOHYPHEN") or line.startswith("COMPOUND"):
            continue
        if "/" in line or "=" in line:   # non-standard hyphenation: not Liang patterns
            continue
        out.append(line)
    return out


def main():
    if "--fetch" in sys.argv or not os.path.isdir(DIR):
        fetch()
    rows, total = [], 0
    out = [a for a in sys.argv[1:] if not a.startswith("--")][0]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// hyphdata.c — generated by ports/books/gen_hyph.py from ports/books/hyph/ (the sources and\n"
                "// their license notices). Do not edit. Each language's patterns: zlib-compressed, space separated.\n"
                "#include <stddef.h>\n\n"
                "typedef struct { const char *lang; const unsigned char *z; unsigned zn, n; int left, right; } hyph_lang_t;\n\n")
        for code, (_, name, lic, left, right) in LANGS.items():
            raw = open(os.path.join(DIR, name), "rb").read()
            text = raw.decode("utf-8") if not name.endswith(".dic") else raw.decode(
                raw.split(b"\n", 1)[0].decode("ascii", "replace").strip().lower().replace("iso8859", "iso-8859") or "utf-8", "replace")
            pats = tex_patterns(text) if name.endswith(".tex") else dic_patterns(text)
            blob = " ".join(pats).encode("utf-8")
            z = zlib.compress(blob, 9)
            total += len(z)
            f.write("static const unsigned char kH_%s[%d] = {\n" % (code, len(z)))
            for k in range(0, len(z), 32):
                f.write("    " + ",".join(str(b) for b in z[k:k + 32]) + ",\n")
            f.write("};\n")
            rows.append((code, len(z), len(blob), left, right))
            print("%-3s %-18s %6d patterns, %7d bytes -> %6d deflated  (%s)" % (code, name, len(pats), len(blob), len(z), lic))
        f.write("\nconst hyph_lang_t bk_hyph[] = {\n")
        for code, zn, n, left, right in rows:
            f.write('    {"%s", kH_%s, %d, %d, %d, %d},\n' % (code, code, zn, n, left, right))
        f.write("    {NULL, NULL, 0, 0, 0, 0},\n};\n")
    print("%s: %d languages, %d bytes" % (out, len(rows), total))


if __name__ == "__main__":
    main()
