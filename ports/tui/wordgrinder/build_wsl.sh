#!/bin/bash
# build_wsl.sh SRC PREFIX OUT — WordGrinder 0.9 (ncurses front end) as one WASI program: Luau
# (Ast, Compiler, VM; errors through nv_try_call/nv_throw, -DNV_SJLJ), cmark, fmt, MiniZip,
# wcwidth, clip (no clipboard), and the application's Lua compiled to bytecode on the PC (the
# Luau compiler stays in for the code WordGrinder builds at run time with loadstring). Links
# ../ncurses and ../deps from PREFIX. Linux wasi-sdk 34 in WSL; C++17 without exceptions.
set -euo pipefail
src="$1"; prefix="$2"; out="$3"; here="$(cd "$(dirname "$0")" && pwd)"
common="$(cd "$here/../../common" && pwd)"
W=/opt/wasi-sdk-34.0-x86_64-linux
B=/root/nv_tui/build/wordgrinder; rm -rf "$B"; mkdir -p "$B/o" "$B/gen"
G="$src/wordgrinder"
L="$G/third_party/luau"

# The application's Lua sources, compiled to Luau bytecode here on the PC (luau_bc: a native
# build of the same Luau, cached in /root/nv_tui/bin) and embedded (lua_table.py): the device
# loads bytecode (-DNV_PRECOMPILED) instead of compiling 17,000 lines of Lua at every start.
LBC=/root/nv_tui/bin/luau_bc
if [ ! -x "$LBC" ] || [ "$here/luau_bc.cpp" -nt "$LBC" ]; then
    mkdir -p /root/nv_tui/bin "$B/lbc"
    LI=(-I"$L/Common/include" -I"$L/Ast/include" -I"$L/Compiler/include")
    for f in "$L"/Ast/src/*.cpp "$L"/Compiler/src/*.cpp; do
        g++ -std=c++17 -O1 -w "${LI[@]}" -c "$f" \
            -o "$B/lbc/$(basename "$(dirname "$(dirname "$f")")")_$(basename "$f" .cpp).o" &
    done
    wait
    g++ -std=c++17 -O1 "${LI[@]}" -o "$LBC" "$here/luau_bc.cpp" "$B"/lbc/*.o
fi
python3 "$here/lua_table.py" "$G" "$LBC" "$B/gen/script_table.h"
# cmark's export header is generated by its CMake build: static library, nothing to export
printf '#pragma once\n#define CMARK_EXPORT\n#define CMARK_NO_EXPORT\n' > "$B/gen/cmark_export.h"

# MiniZip's headers first: libzip (in PREFIX, for sc-im) also has a zip.h
FLAGS=(--target=wasm32-wasip1 --sysroot="$W/share/wasi-sysroot" -Os -w -DNDEBUG
       -D_WASI_EMULATED_SIGNAL -D_WASI_EMULATED_PROCESS_CLOCKS -D_WASI_EMULATED_GETPID
       -D_WASI_EMULATED_MMAN -DUSE_FILE32API -I"$G/third_party/minizip" -I"$B/gen"
       -I"$here/../compat" -I"$prefix/include" -I"$prefix/include/ncursesw" -I"$common"
       -include nv_posix.h)
CXXF=("${FLAGS[@]}" -include stdlib.h -std=c++17 -fno-exceptions -DNV_SJLJ -DLUA_USE_LONGJMP=1 -DFMT_EXCEPTIONS=0
      -I"$L/Common/include" -I"$L/Ast/include" -I"$L/Compiler/include" -I"$L/VM/include"
      -I"$L/VM/src" -I"$G/third_party/fmt/include" -I"$G/third_party/clip"
      -I"$G/third_party/cmark/src" -I"$G/third_party/minizip" -I"$G/third_party/libstb"
      -I"$G/src/c" -I"$G/src/c/luau-em" -I"$B/gen")
CF=("${FLAGS[@]}" -I"$G/third_party/cmark/src" -I"$G/third_party/minizip" -DNOCRYPT -DCMARK_STATIC_DEFINE)
CC="$W/bin/clang"; CXX="$W/bin/clang++"

n=0
cxx() { "$CXX" "${CXXF[@]}" "$@"; }
for f in "$L"/Ast/src/*.cpp "$L"/Compiler/src/*.cpp "$L"/VM/src/*.cpp; do
    cxx -c -o "$B/o/luau_$(basename "$(dirname "$(dirname "$f")")")_$(basename "$f" .cpp).o" "$f" &
    n=$((n + 1)); [ $((n % 8)) -eq 0 ] && wait
done
wait
for f in blocks buffer cmark cmark_ctype commonmark houdini_href_e houdini_html_e houdini_html_u html \
         inlines iterator latex man node references render scanners utf8 xml; do
    "$CC" "${CF[@]}" -c -o "$B/o/cmark_$f.o" "$G/third_party/cmark/src/$f.c" &
done
for f in ioapi unzip zip; do "$CC" "${CF[@]}" -c -o "$B/o/mz_$f.o" "$G/third_party/minizip/$f.c" & done
"$CC" "${CF[@]}" -c -o "$B/o/stb.o" "$G/third_party/libstb/stb.c" &
wait
cxx -c -o "$B/o/fmt_format.o" "$G/third_party/fmt/src/format.cc" &
cxx -c -o "$B/o/wcwidth.o" "$G/third_party/wcwidth/wcwidth.cc" &
for f in clip image clip_none; do cxx -c -o "$B/o/clip_$f.o" "$G/third_party/clip/$f.cpp" & done
cxx -c -o "$B/o/lauxlib.o" "$G/src/c/luau-em/lauxlib.cc" &
wait
WGF=(-DNV_PRECOMPILED -DFILEFORMAT=8 -DVERSION=0.9 -DARCH=nucleoos -DFRONTEND=ncurses
     -DDEFAULT_DICTIONARY_PATH=/dict/words -DCMARK_STATIC_DEFINE)
for f in main lua utils screen word zip filesystem cmark clipboard; do
    cxx "${WGF[@]}" -c -o "$B/o/wg_$f.o" "$G/src/c/$f.cc" &
done
cxx "${WGF[@]}" -c -o "$B/o/wg_dpy.o" "$G/src/c/arch/ncurses/dpy.cc" &
wait
"$CC" "${FLAGS[@]}" -c -o "$B/o/nv_posix.o" "$here/../compat/nv_posix.c"
"$CC" "${FLAGS[@]}" -c -o "$B/o/nv_localtime.o" "$here/../compat/nv_localtime.c"

STRIP=(-Wl,--strip-all); [ -n "${NV_KEEP_NAMES:-}" ] && STRIP=()   # NV_KEEP_NAMES=1: function names kept
# stdin and TIOCGWINSZ through ../compat/nv_tty.c; -u: see ../scim/build_wsl.sh
TTY_LD=(-Wl,--wrap=read,--wrap=poll,--wrap=select,--wrap=ioctl -Wl,-u,read,-u,poll,-u,select,-u,ioctl)
LT_LD=(-Wl,--wrap=localtime,--wrap=localtime_r,--wrap=mktime)   # local time: ../compat/nv_localtime.c
"$CXX" "${CXXF[@]}" -Wl,-z,stack-size=262144 "${STRIP[@]}" "${TTY_LD[@]}" "${LT_LD[@]}" -o "$out" "$B"/o/*.o \
    -L"$prefix/lib" -lncursesw -lnvtty -lz -lm \
    -lwasi-emulated-signal -lwasi-emulated-process-clocks -lwasi-emulated-getpid -lwasi-emulated-mman
echo "  wordgrinder: $(stat -c %s "$out") bytes"
