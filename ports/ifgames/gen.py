def table(rows):
    return "\n".join(f"| `{a}` | {('`' + b + '`') if b else ''} | {c} |" for a, b, c in rows)


def guides(g):
    iname, ilic, iurl = INTERP[interp(g)]
    italian = g["lang"] == "it"
    nc = g.get("nc") and "non-commercial" not in g["license"]
    quote = g.get("license_quote", "")
    f = dict(g, slug=g["slug"], lang_it=LANG_IT[g["lang"]], lang_en=LANG_EN[g["lang"]],
             fmt=FORMAT_NAMES[g["format"]], iname=iname, ilic=ilic, iurl=iurl,
             commands_it=table(CMDS_IT_GAME if italian else CMDS_IT_FOR_EN_GAME),
             commands_en=table(CMDS_EN_FOR_IT_GAME if italian else CMDS_EN),
             license_line_it=f"Licenza: **{g['license']}**" + (" (solo uso non commerciale)." if nc else "."),
             license_line_en=f"Licence: **{g['license']}**" + (" (non-commercial use only)." if nc else "."),
             mod_it=("Il file della storia è ridistribuito senza le immagini, che qui non si possono mostrare (resta il "
                     "codice di gioco), come la licenza consente; l'interprete è invariato." if g.get("strip_blorb") else
                     "Gioco e interprete sono ridistribuiti invariati; NucleoOS aggiunge solo l'avvio e l'accesso "
                     "al file della storia incorporato."),
             mod_en=("The story file is redistributed without its pictures (game code only; they cannot be shown "
                     "here), as the licence allows; the interpreter is unmodified." if g.get("strip_blorb") else
                     "Game and interpreter are redistributed unmodified; NucleoOS only adds the launcher and access "
                     "to the embedded story file."),
             license_quote_block=(f"> {quote}" if quote else ""))
    return GUIDE_IT.format(**f), GUIDE_EN.format(**f)


def games_md(games):
    out = ["# Interactive fiction catalog", "",
           "One Terminal app per game (`apps/if-<slug>/`), built by `build.sh` from `games.json`.",
           "Every licence below was checked at the URL given; the quote is the statement relied on.",
           "Interpreters: Frotz 2.55 dumb (z-code, GPL-2.0-or-later), Glulxe + CheapGlk (Glulx, MIT);",
           "the story is stored raw-deflated in the module and inflated at start with miniz tinfl (MIT).",
           "Rebuild: `bash ports/ifgames/build.sh`, test on the PC: `bash ports/ifgames/test.sh`.", "",
           "| App | Title | Author | Year | Format | Lang | Licence | Story sha256 |",
           "|---|---|---|---|---|---|---|---|"]
    for g in games:
        lic = g["license"] + (" **NC**" if g.get("nc") else "")
        out.append(f"| if-{g['slug']} | {g['title']} | {g['author']} | {g['year']} | {g['format']} | "
                   f"{g['lang']} | [{lic}]({g['license_url']}) | `{g['sha256']}` |")
    out += ["", "## Licence statements", ""]
    for g in games:
        src = f"{g['url']} ({g['member']})" if g.get("zip") else g["url"]
        note = f" Note: {g['note']}." if g.get("note") else ""
        out.append(f"- **{g['title']}** — {g['license']}, <{g['license_url']}>: "
                   f"\"{g.get('license_quote', '')}\" — story: <{src}>, IFDB: <{g['source']}>.{note}")
    try:
        rej = json.load(open(f"{HERE}/rejected.json", encoding="utf-8"))
    except FileNotFoundError:
        rej = []
    if rej:
        out += ["", "## Not included", "", "| Game | Author | Reason |", "|---|---|---|"]
        out += [f"| {r['title']} | {r['author']} | {r['reason']} |" for r in rej]
    write(f"{HERE}/GAMES.md", "\n".join(out) + "\n")


def catalog(games):
    cat = {}
    for g in games:
        d = descriptions(g)
        cat[f"if-{g['slug']}"] = {"category": "terminal", "featured": False, "rating": g.get("rating", 4.0),
                                  "regions": ["*"], "names": {"en": g["title"], "it": g["title"]},
                                  "descriptions": d}
    write(f"{HERE}/catalog_entries.json", json.dumps(cat, indent=2, ensure_ascii=False) + "\n")


def main():
    games = json.load(open(f"{HERE}/games.json", encoding="utf-8"))
    for g in games:
        assert len(f"if-{g['slug']}") <= 31 and all(c in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in g["slug"])
    games_md(games)
    catalog(games)
    sel = [g for g in games if not sys.argv[1:] or g["slug"] in sys.argv[1:]]
    for g in sel:
        gen_c(g)
        d = f"{ROOT}/apps/if-{g['slug']}"
        write(f"{d}/manifest.json", manifest(g))
        it, en = guides(g)
        write(f"{d}/GUIDE.md", it)
        write(f"{d}/GUIDE.en.md", en)
        ic = g["icon"]
        print(g["slug"], interp(g), ic["label"].replace(" ", "_"), ic["bg"], ic["fg"])


if __name__ == "__main__":
    main()
