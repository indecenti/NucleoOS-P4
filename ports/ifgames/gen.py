"""gen.py — generate everything of the IF catalog that is not a binary, from games.json.

    python ports/ifgames/gen.py [slug ...]        (called by build.sh; default: every game)

For each game: ports/_src/ifgames_gen/<slug>.c (credits + #embed of the raw-deflated story, whole; a Blorb marked
"strip_blorb" keeps only its executable chunk, when its pictures would not fit and the licence allows it),
apps/if-<slug>/{manifest.json,GUIDE.md,GUIDE.en.md}.
Always rewrites ports/ifgames/GAMES.md and ports/ifgames/catalog_entries.json for the whole list.
Prints one line per selected game for build.sh: "slug interpreter label bg fg".
"""
import hashlib
import json
import os
import struct
import zlib
import sys

HERE = os.path.dirname(os.path.abspath(__file__)).replace("\\", "/")
PORTS = os.path.dirname(HERE)
ROOT = os.path.dirname(PORTS)
SRC = PORTS + "/_src/ifgames"
GEN = PORTS + "/_src/ifgames_gen"

FORMAT_NAMES = {"z3": "Z-machine v3", "z5": "Z-machine v5", "z8": "Z-machine v8",
                "zblorb": "Z-machine (Blorb)", "ulx": "Glulx", "gblorb": "Glulx (Blorb)"}
LANG_EN = {"en": "English", "it": "Italian"}
LANG_IT = {"en": "inglese", "it": "italiano"}
INTERP = {"frotz": ("Frotz 2.55", "GPL-2.0-or-later", "https://gitlab.com/DavidGriffith/frotz"),
          "glulxe": ("Glulxe + CheapGlk", "MIT", "https://github.com/erkyrath/glulxe")}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def blorb_exec(data, want):
    """The executable chunk (ZCOD / GLUL) of a Blorb file."""
    if data[:4] != b"FORM" or data[8:12] != b"IFRS":
        return data
    pos = 12
    while pos + 8 <= len(data):
        cid, ln = data[pos:pos + 4], struct.unpack(">I", data[pos + 4:pos + 8])[0]
        if cid == want:
            return data[pos + 8:pos + 8 + ln]
        pos += 8 + ln + (ln & 1)
    raise SystemExit(f"blorb without {want!r} chunk")


def story_bytes(g):
    path = f"{SRC}/{g['file']}"
    data = open(path, "rb").read()
    sha = hashlib.sha256(data).hexdigest()
    if sha != g["sha256"]:
        raise SystemExit(f"{g['slug']}: sha256 {sha} != games.json {g['sha256']}")
    fmt = g["format"]
    if g.get("strip_blorb"):   # only for licences that allow adaptations (never ND)
        assert "ND" not in g["license"]
        return (blorb_exec(data, b"GLUL"), "ulx") if fmt == "gblorb" else (blorb_exec(data, b"ZCOD"), "z")
    return data, fmt


def interp(g):
    return "glulxe" if g["format"] in ("ulx", "gblorb") else "frotz"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def gen_c(g):
    data, ext = story_bytes(g)
    # Stored raw-deflated (inflated once at start by tinfl): about 3x smaller modules, and the
    # bigger games fit the 2 MB app.wasm cap.
    co = zlib.compressobj(9, zlib.DEFLATED, -15)
    packed = co.compress(data) + co.flush()
    story = f"{GEN}/{g['slug']}.story.deflate"
    if not os.path.exists(story) or open(story, "rb").read() != packed:
        open(story, "wb").write(packed)
    lic = g["license"] + (" (non-commercial)" if g.get("nc") else "")
    credit = f"by {g['author']} ({g['year']}) - {lic}"
    write(f"{GEN}/{g['slug']}.c",
          f"// generated by ports/ifgames/gen.py - {g['title']}\n"
          f"#define NV_IF_TITLE {c_str(g['title'])}\n"
          f"#define NV_IF_CREDIT {c_str(credit)}\n"
          f"#define NV_IF_STORY_NAME {c_str(g['slug'] + '.' + ext)}\n"
          f"#define NV_IF_STORY_SIZE {len(data)}u\n"
          f"#define NV_IF_{interp(g).upper()}\n"
          f"static const unsigned char nv_if_story_z[] = {{\n#embed {c_str(story)}\n}};\n"
          f"#include \"nv_if_main.c\"\n")


def descriptions(g):
    tip_en = f"Type if-{g['slug']} in the Terminal or tap the icon."
    tip_it = f"Scrivi if-{g['slug']} nel Terminale o tocca l'icona."
    nc_en = " Non-commercial licence." if g.get("nc") else ""
    nc_it = " Licenza non commerciale." if g.get("nc") else ""
    return {
        "en": f"{g['desc_en']} Text adventure in {LANG_EN[g['lang']]} ({g['author']}, {g['year']}).{nc_en} {tip_en}",
        "it": f"{g['desc_it']} Avventura testuale in {LANG_IT[g['lang']]} ({g['author']}, {g['year']}).{nc_it} {tip_it}",
    }


def manifest(g):
    name, ilic, _ = INTERP[interp(g)]
    d = descriptions(g)
    m = {
        "id": f"if-{g['slug']}",
        "name": g["title"],
        "version": "1.0",
        "abi": 8,
        "console": True,
        "ram_budget": 8388608 if interp(g) == "glulxe" else 4194304,
        "stack_kb": 256 if interp(g) == "glulxe" else 64,
        "permissions": ["fs"],
        "author": f"{g['author']}; interpreter: {name}",
        "license": f"{g['license']} (game), {ilic} (interpreter)",
        "source": g["source"],
        "description": d["en"],
        "descriptions": d,
    }
    return json.dumps(m, indent=2, ensure_ascii=False) + "\n"


