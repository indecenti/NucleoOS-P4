"""gen_fontdata.py — the fonts of ports/zim/biblioteca/fonts as C arrays (bib_font_*), for the build.

    python ports/zim/biblioteca/gen_fontdata.py OUT.c
"""
import os
import sys

FONTS = [("bib_font_sans", "sans.ttf"), ("bib_font_bold", "sans-bold.ttf"), ("bib_font_italic", "sans-italic.ttf"),
         ("bib_font_bolditalic", "sans-bolditalic.ttf"), ("bib_font_mono", "mono.ttf")]


def main():
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fonts")
    with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by ports/zim/biblioteca/gen_fontdata.py from fonts/ (Noto, SIL OFL 1.1). Do not edit.\n")
        total = 0
        for name, file in FONTS:
            with open(os.path.join(here, file), "rb") as src:
                data = src.read()
            total += len(data)
            f.write("const unsigned char %s[%d] __attribute__((aligned(4))) = {\n" % (name, len(data)))
            for i in range(0, len(data), 32):
                f.write(",".join(str(b) for b in data[i:i + 32]) + ",\n")
            f.write("};\n")
    print("%s: %d fonts, %d bytes" % (sys.argv[1], len(FONTS), total))


if __name__ == "__main__":
    main()
