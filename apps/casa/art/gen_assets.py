#!/usr/bin/env python3
"""gen_assets.py - Casa: lettering and icons as RGB565 atlases for nv_gfx_sprite (ABI 15).

The 5x7 system font has no lowercase, accents or degree sign, and Home Assistant names need all
three. So the app draws Montserrat Bold (SIL Open Font License, shipped with LVGL in
managed_components) and Material Design Icons (Apache 2.0, system/icons/mdi) from atlases.

Sprites are magenta-keyed with no alpha, so anti-aliasing is baked in two flavours and the
sprite tint does the rest:
  light (*l.565): white on black, coverage a -> grey a. Tint = text colour: correct on near-black
                  panels (the app's dark tiles).
  dark  (*d.565): black on white, coverage a -> grey 1-a. Tint = the tile colour: dark text on a
                  lit tile of any colour.
Pixels under 20 % coverage are key (transparent).

Writes img/f{s,m,l}{l,d}.565, img/ic{l,d}.565 and casa_assets.h. Run from the repo root:

    python apps/casa/art/gen_assets.py
"""
import os
import struct

import fitz
import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(APP))
FONT = os.path.join(ROOT, "managed_components", "lvgl__lvgl", "tests", "src", "test_files", "fonts",
                    "Montserrat-Bold.ttf")
MDI = os.path.join(ROOT, "system", "icons", "mdi", "svg")
SIZES = [("fs", 17), ("fm", 22), ("fl", 38)]
BIG_ONLY = set(chr(c) for c in range(32, 127)) | {"°"}   # fl: numbers and units
EXTRA = "→…–’"          # arrow, ellipsis, en dash, apostrophe
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0xA0, 0x100)] + list(EXTRA)
ICON_PX = 36
ICON_COLS = 13
ICONS = ["lightbulb-outline", "lightbulb-on", "toggle-switch-off-outline", "toggle-switch-outline", "fan-off", "fan",
         "window-shutter", "window-shutter-open", "garage", "garage-open", "thermostat", "lock",
         "lock-open-variant", "speaker", "speaker-play", "robot-vacuum", "palette", "script-text-play",
         "thermometer", "water-percent", "flash", "door-closed", "door-open", "motion-sensor",
         "motion-sensor-off", "water-alert", "water-off", "window-closed-variant", "window-open-variant", "eye",
         "alert-circle-outline", "minus", "plus", "chevron-left", "chevron-right", "home-assistant",
         "lan-disconnect", "gauge"]
KEY = 0xF81F
CUT = 0.20


def to565(g):
    g = g.astype(np.uint16)
    return ((g & 0xF8) << 8) | ((g & 0xFC) << 3) | (g >> 3)


def write_pair(name, cov):
    """cov: float coverage 0..1 (H x W) -> img/<name>l.565 and img/<name>d.565."""
    h, w = cov.shape
    for fam, grey in (("l", cov * 255.0), ("d", (1.0 - cov) * 255.0)):
        px = to565(np.clip(np.rint(grey), 0, 255))
        px[cov < CUT] = KEY
        with open(os.path.join(APP, "img", name + fam + ".565"), "wb") as f:
            f.write(struct.pack("<HH", w, h))
            f.write(px.astype("<u2").tobytes())


def glyph(font, ch):
    if not ch.strip():
        return np.zeros((1, 1), np.float32), 0, 0, font.getlength(ch)
    l, t, r, b = font.getbbox(ch) if ch.strip() else (0, 0, 1, 1)
    l, t = l - 1, t - 1
    w, h = max(1, r - l + 1), max(1, b - t + 1)
    m = Image.new("L", (w, h), 0)
    if ch.strip():
        ImageDraw.Draw(m).text((-l, -t), ch, font=font, fill=255)
    return np.asarray(m, dtype=np.float32) / 255.0, l, t, font.getlength(ch)


def main():
    os.makedirs(os.path.join(APP, "img"), exist_ok=True)
    out = ["// casa_assets.h - generated by art/gen_assets.py: do not edit.",
           "// Montserrat Bold (OFL) atlases f<size><l|d> and MDI icons (Apache 2.0) ic<l|d>.",
           "// Glyph: atlas x, y, w, h, offset from the pen (x) and from the line top (y), advance in 1/4 px.",
           "typedef struct { short x, y; unsigned char w, h; signed char ox, oy; unsigned char adv; } Glyph;",
           "// Glyph index: ASCII c - 32; Latin-1 95 + (c - 0xA0); then " + " ".join("U+%04X" % ord(c) for c in EXTRA) + ".",
           "#define FONT_GLYPHS %d" % len(CHARS),
           "#define GLYPH_EXTRA 191",
           "static const unsigned short k_extra[%d] = { %s };" % (len(EXTRA), ", ".join("0x%04X" % ord(c) for c in EXTRA))]
    for name, px in SIZES:
        font = ImageFont.truetype(FONT, px)
        cells = [glyph(font, c if name != "fl" or c in BIG_ONLY else " ") for c in CHARS]
        W, x, y, rowh, place = 512, 0, 0, 0, []
        for cov, *_ in cells:
            if x + cov.shape[1] > W:
                x, y, rowh = 0, y + rowh + 1, 0
            place.append((x, y))
            x += cov.shape[1] + 1
            rowh = max(rowh, cov.shape[0])
        atlas = np.zeros((y + rowh, W), np.float32)
        for (cov, *_), (ax, ay) in zip(cells, place):
            atlas[ay:ay + cov.shape[0], ax:ax + cov.shape[1]] = cov
        write_pair(name, atlas)
        asc, desc = font.getmetrics()
        out.append("static const Glyph k_%s[FONT_GLYPHS] = {" % name)
        rows = ["{%d,%d,%d,%d,%d,%d,%d}" % (ax, ay, cov.shape[1], cov.shape[0], l, t, round(adv * 4))
                for (cov, l, t, adv), (ax, ay) in zip(cells, place)]
        for i in range(0, len(rows), 8):
            out.append("    " + ", ".join(rows[i:i + 8]) + ",")
        out.append("};")
        out.append("#define %s_LINE %d" % (name.upper(), asc + desc))
        print(name, W, "x", atlas.shape[0])
    # icons: a grid of ICON_PX square cells, 4x supersampled from the SVG
    rows = -(-len(ICONS) // ICON_COLS)              # a grid: assets are at most 512 x 512
    strip = np.zeros((rows * (ICON_PX + 1), ICON_COLS * (ICON_PX + 1)), np.float32)
    for i, n in enumerate(ICONS):
        doc = fitz.open(os.path.join(MDI, n + ".svg"))
        page = doc[0]
        z = ICON_PX * 4 / max(page.rect.width, page.rect.height)
        pix = page.get_pixmap(matrix=fitz.Matrix(z, z), alpha=True)
        a = np.frombuffer(pix.samples, np.uint8).reshape(pix.height, pix.width, pix.n)[..., -1]
        img = Image.fromarray(a).resize((ICON_PX, ICON_PX), Image.BOX)
        ox, oy = (i % ICON_COLS) * (ICON_PX + 1), (i // ICON_COLS) * (ICON_PX + 1)
        strip[oy:oy + ICON_PX, ox:ox + ICON_PX] = np.asarray(img, np.float32) / 255.0
    write_pair("ic", strip)
    out.append("#define ICON_PX %d" % ICON_PX)
    out.append("#define ICON_COLS %d" % ICON_COLS)
    out.append("enum { " + ", ".join("IC_" + n.upper().replace("-", "_") for n in ICONS) + " };")
    with open(os.path.join(APP, "casa_assets.h"), "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("icons", len(ICONS))


if __name__ == "__main__":
    main()
